"""Rebuild references/tools.md from the header of every tool in scripts/ (run after adding or changing a tool).

Usage: python -I <skill>/scripts/make-tools-index.py
Takes each file's first usage line and the first sentence of its description.
"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'references', 'tools.md')
GROUPS = [('scripts/', '', 'Measurement, crawling, judging, reporting'),
          ('scripts/wp/', 'wp', 'Site content through the MCP and REST (all reversible, dry run first)'),
          ('scripts/checks/', 'checks', 'Browser checks (headless Chrome; screenshots to ./shots)')]


def header(path):
    lines = open(path, encoding='utf-8', errors='replace').read().splitlines()[:30]
    text = []
    for l in lines:
        s = l.strip()
        if s.startswith('#!') or s in ('"""', "'''"):
            continue
        if s.startswith(('#', '//', '"""', "'''", '*')) or (text and s and not re.match(r'^(import|from|const|let|var|function|[A-Z_]+ ?=|\w+ ?=)', s)):
            text.append(re.sub(r'^(#|//|"""|\'\'\'|\*)\s?', '', s).rstrip('"').strip())
        elif text:
            break
    usage = next((t for t in text if t.lower().startswith('usage')), '')
    desc = ' '.join(t for t in text if t and not t.lower().startswith('usage'))
    parts = re.split(r'(?<=\.)\s', desc) if desc else ['']
    first = parts[0]
    if len(first) < 40 and len(parts) > 1:
        first += ' ' + parts[1]
    return usage, first[:220]


out = ['# Tools in scripts/', '',
       'Generated by `scripts/make-tools-index.py` from each file\'s header; the header itself has the details. Run',
       'everything from the site folder; `$S` is the skill\'s `scripts/` folder. Python tools with `python -I` unless',
       'noted (Pillow, fonttools). JavaScript tools need `npm install` once in `scripts/`.', '']
for label, sub, title in GROUPS:
    out += ['## ' + title, '', '| Tool | What it does | Usage |', '|---|---|---|']
    for f in sorted(glob.glob(os.path.join(HERE, sub, '*.*'))):
        name = os.path.basename(f)
        if not name.endswith(('.py', '.js', '.sh')) or name.startswith('_') or name == 'sitecfg.py':
            continue
        usage, first = header(f)
        usage = re.sub(r'^usage( \(from the [a-z ]+\))?:\s*', '', usage, flags=re.I).replace('|', '\\|')
        out.append('| `%s%s` | %s | `%s` |' % (label, name, first.replace('|', '\\|') or '(see file)', usage[:150]))
    out.append('')
out += ['Helpers: `scripts/wp/sitecfg.py` (reads site.json; `--shell` for the bash tools), `scripts/checks/_lib.js`',
        '(Chrome path, ./shots, site.json selectors).', '']
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print('wrote', OUT, sum(1 for l in out if l.startswith('| `')), 'tools')
